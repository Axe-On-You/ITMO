import numpy as np


# ==========================================
# Целевая функция
# ==========================================

def objective(x, y):
    """
    f(x,y) = 10^-2 * (8x^2 + 2xy + 9x + 2y + 1)
    """
    return 1e-2 * (8 * x**2 + 2 * x * y + 9 * x + 2 * y + 1)


# ==========================================
# Градиент функции
# ==========================================

def grad_objective(x, y):
    """
    Градиент функции:
    df/dx = 0.01 * (16x + 2y + 9)
    df/dy = 0.01 * (2x + 2)
    """
    df_dx = 1e-2 * (16 * x + 2 * y + 9)
    df_dy = 1e-2 * (2 * x + 2)

    return np.array([df_dx, df_dy])


